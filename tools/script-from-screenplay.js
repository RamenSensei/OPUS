#!/usr/bin/env node
/* ==========================================================================
   tools/script-from-screenplay.js — design/screenplay.json → js/script.js.
   Carries segments, durations, engine transitions and every text cue (with
   its exact placement, ink, seal and font). Hand edits to js/script.js are
   overwritten, so put lasting changes in the screenplay or in OVERRIDES below.
     node tools/script-from-screenplay.js
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const sp = JSON.parse(fs.readFileSync(path.join(ROOT, 'design/screenplay.json'), 'utf8'));

// Lasting per-cue additions that the screenplay does not carry (yet), keyed
// "segment-id@t". sub_ink: 'dark' sets the Chinese subtitle in sumi where its
// band (y 960–1040) is pale paper: the 藍 panel of 月に雁 and the blank washi
// after the unprinting. (序's cue is ink 'dark' but its subtitle sits over the
// night pond, so the poem's ink cannot be reused for the subtitle.)
const OVERRIDES = {
  'atozuri@13.6': { sub_ink: 'dark' },
  'fuji-no-keburi@20.8': { sub_ink: 'dark' },
};

const KIND = { haiku: 'haiku', waka: 'waka', narration: 'narration', title: 'title', caption: 'caption', kanshi: 'kanshi', letter: 'letter' };

function cueOut(c, segId) {
  c = { ...c, ...(OVERRIDES[`${segId}@${c.t}`] || {}) };
  const kind = KIND[c.kind] || 'narration';
  const o = { t: c.t, dur: c.dur, kind, ja: c.ja };
  if (c.author) o.author = c.author;
  if (c.seal || c.seal === false) o.seal = c.seal;
  if (c.en) o.en = c.en;
  if (c.seal_style) o.seal_style = c.seal_style;
  if (c.zh) o.zh = c.zh;
  if (c.position) o.position = c.position;
  if (c.x != null) o.x = c.x;
  if (c.y != null) o.y = c.y;
  if (c.ink) o.ink = c.ink;
  if (c.size) o.size = c.size;
  if (c.font) o.font = /brush|yuji/i.test(c.font) ? 'brush' : /mincho/i.test(c.font) ? 'mincho' : c.font;
  if (c.layout) o.layout = c.layout;
  if (c.sigAt) o.sigAt = c.sigAt;
  if (c.chirashi) o.chirashi = c.chirashi;
  if (c.sub_ink) o.sub_ink = c.sub_ink;
  // Kaguya's letter and the title are brushed (text_style.fonts)
  if (!o.font && (kind === 'title' || kind === 'letter' || /かぐや姫の文/.test(c.author || ''))) o.font = 'brush';
  return o;
}

function transitionOut(prev) {
  const n = prev.engine_transition_next;
  if (!n) return { type: 'cut', dur: 0 };
  const t = { type: n.type || 'cut', dur: n.dur || 0 };
  if (n.center) t.center = n.center;
  if (n.ring != null) t.ring = n.ring;
  if (n.rows) t.rows = n.rows;
  if (n.color) t.color = /^#/.test(n.color) ? n.color : `@${n.color}`;
  if (n.soft != null) t.soft = n.soft;
  return t;
}

const J = (v) => JSON.stringify(v);
const out = [];
out.push('/* ==========================================================================');
out.push(`   script.js — the running order and every word the film shows.`);
out.push('   GENERATED by tools/script-from-screenplay.js from design/screenplay.json.');
out.push('   ========================================================================== */');
out.push('(function (TSUKI) {');
out.push("  'use strict';");
out.push('  const C = TSUKI.C;');
out.push('  TSUKI.SCRIPT = {');
out.push(`    title: ${J({ ja: sp.title.ja, sub: sp.title.subtitle_ja, zh: sp.title.zh, en: sp.title.en, reading: sp.title.reading })},`);
out.push(`    curtain: { columns: ${J([sp.title.ja, (sp.title.subtitle_ja || '').replace(/[〜~]/g, '')])} },`);
out.push(`    posterT: ${sp.poster_t != null ? sp.poster_t : 21},`);
out.push('    segments: [');
sp.segments.forEach((s, i) => {
  out.push('      {');
  out.push(`        id: ${J(s.id)}, title_ja: ${J(s.title_ja)}, title_zh: ${J(s.title_zh)}, duration: ${s.duration},`);
  out.push(`        shot: ${J(s.shot || '')},`);
  if (i > 0) {
    let tr = J(transitionOut(sp.segments[i - 1]));
    tr = tr.replace(/"@(\w+)"/g, (m, k) => `C.${k}`);
    out.push(`        transition: ${tr},`);
  }
  out.push('        text: [');
  for (const c of s.text_cues || []) out.push(`          ${J(cueOut(c, s.id))},`);
  out.push('        ],');
  out.push('      },');
});
out.push('    ],');
out.push('  };');
out.push('})(window.TSUKI = window.TSUKI || {});');
fs.writeFileSync(path.join(ROOT, 'js/script.js'), out.join('\n') + '\n');
const total = sp.segments.reduce((a, s) => a + s.duration, 0);
console.log(`wrote js/script.js: ${sp.segments.length} segments, ${total}s, ${sp.segments.reduce((a, s) => a + (s.text_cues || []).length, 0)} text cues`);
